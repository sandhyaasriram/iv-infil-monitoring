import pandas as pd
import numpy as np
import m2cgen as m2c
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.metrics import classification_report, f1_score

WINDOW_S = 25

def extract_window_features(group):
    feats, labels, trial_ids, conditions = [], [], [], []
    temp = group['temperature_c'].values
    press = group['pressure_adc'].values
    lab = group['label'].values
    n = len(group)

    for start in range(0, n - WINDOW_S, WINDOW_S):
        t_win = temp[start:start+WINDOW_S]
        p_win = press[start:start+WINDOW_S]
        l_win = lab[start:start+WINDOW_S]

        def safe_stats(x, prefix):
            if np.all(np.isnan(x)):
                return {f'{prefix}_mean': np.nan, f'{prefix}_std': np.nan,
                        f'{prefix}_slope': np.nan, f'{prefix}_min': np.nan,
                        f'{prefix}_max': np.nan}
            return {
                f'{prefix}_mean': np.nanmean(x),
                f'{prefix}_std': np.nanstd(x),
                f'{prefix}_slope': np.polyfit(np.arange(len(x)), np.nan_to_num(x, nan=np.nanmean(x)), 1)[0],
                f'{prefix}_min': np.nanmin(x),
                f'{prefix}_max': np.nanmax(x),
            }

        row = {}
        row.update(safe_stats(t_win, 'temp'))
        row.update(safe_stats(p_win, 'press'))
        row['sensor_missing_temp'] = int(np.all(np.isnan(t_win)))
        row['sensor_missing_press'] = int(np.all(np.isnan(p_win)))

        feats.append(row)
        labels.append(np.bincount(l_win).argmax())
        trial_ids.append(group['trial_id'].iloc[0])
        conditions.append(group['condition'].iloc[0])

    out = pd.DataFrame(feats)
    out['label'] = labels
    out['trial_id'] = trial_ids
    out['condition'] = conditions
    return out

print("Loading dataset...")
df = pd.read_csv('synthetic_iv_infiltration_dataset.csv')

print("Extracting window features...")
feature_dfs = [extract_window_features(g) for _, g in df.groupby('trial_id')]
features = pd.concat(feature_dfs, ignore_index=True)

feature_cols = [c for c in features.columns if c not in ['label', 'trial_id', 'condition']]
X = features[feature_cols]
y = features['label']

print(f"Dataset shape: {X.shape}")

# Train the pipeline
print("Training TinyML Random Forest...")
# Use a tiny RF to ensure the generated C++ header isn't too huge for ESP32 flash memory
clf = RandomForestClassifier(n_estimators=30, max_depth=5, class_weight='balanced', random_state=42)
imputer = SimpleImputer(strategy='mean')

X_imputed = imputer.fit_transform(X)
clf.fit(X_imputed, y)

# Evaluate on training data just to show it learned
y_pred = clf.predict(X_imputed)
print(classification_report(y, y_pred, target_names=['none','early','moderate','severe']))

print("Exporting model to C++ using m2cgen...")
# We only export the classifier. The ESP32 code will handle imputation manually using the learned means.
code = m2c.export_to_c(clf)

header_content = f"""#ifndef TINYML_MODEL_H
#define TINYML_MODEL_H

// This file was auto-generated by m2cgen

// Imputation means (calculated during training):
"""

for i, col in enumerate(feature_cols):
    header_content += f"const float IMPUTE_MEAN_{col.upper()} = {imputer.statistics_[i]:.6f};\n"

header_content += """
// Feature indices:
// 0: temp_mean, 1: temp_std, 2: temp_slope, 3: temp_min, 4: temp_max
// 5: press_mean, 6: press_std, 7: press_slope, 8: press_min, 9: press_max
// 10: sensor_missing_temp, 11: sensor_missing_press

"""
header_content += code
header_content += "\n#endif\n"

with open('firmware/sketch/tinyml_model.h', 'w') as f:
    f.write(header_content)

print("Successfully exported firmware/sketch/tinyml_model.h")
